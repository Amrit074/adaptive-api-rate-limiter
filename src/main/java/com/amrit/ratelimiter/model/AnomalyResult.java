package com.amrit.ratelimiter.model;

import jakarta.persistence.*;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Data;
import lombok.NoArgsConstructor;

import java.time.LocalDateTime;

/**
 * Stores the output of each ML anomaly detection run.
 * The Python service writes to this table after scoring each IP.
 * The Spring Boot AnomalySyncService reads this table to push
 * flagged IPs into the Redis blocklist.
 */
@Entity
@Table(name = "anomaly_result", indexes = {
    @Index(name = "idx_ip_detected", columnList = "clientIp, detectedAt")
})
@Data
@Builder
@NoArgsConstructor
@AllArgsConstructor
public class AnomalyResult {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @Column(nullable = false, length = 45)
    private String clientIp;

    // Isolation Forest anomaly score (-1 = anomaly, 1 = normal)
    @Column(nullable = false)
    private Double anomalyScore;

    // True if this IP was flagged as anomalous by the ML model
    @Column(nullable = false)
    private Boolean isAnomalous;

    // Reason string generated by Python service
    @Column(length = 500)
    private String reason;

    @Column(nullable = false)
    private LocalDateTime detectedAt;

    // True once Spring has pushed this into Redis blocklist
    @Column(nullable = false)
    @Builder.Default
    private Boolean syncedToRedis = false;
}
